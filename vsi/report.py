"""Fill the automatic parts of the report: status (progress + next step) and results (table + charts).

Only text between VSI markers is replaced, everything the student wrote stays:
    <!-- vsi:status:start --> … <!-- vsi:status:end -->
    <!-- vsi:results:start --> … <!-- vsi:results:end -->
README.md is used when it has the markers (the VSI template has them); otherwise docs/REPORT.md.
Charts are copied from results/ (not committed) to docs/figures/ (committed) so they show on GitHub.
"""

from __future__ import annotations

import csv
import re
import shutil
from datetime import date
from pathlib import Path

from . import progress

BLOCKS = ("status", "results")


def _markers(name: str) -> tuple[str, str]:
    return f"<!-- vsi:{name}:start -->", f"<!-- vsi:{name}:end -->"


def target_file(root: Path) -> Path:
    readme = root / "README.md"
    if readme.exists() and _markers("results")[0] in readme.read_text(encoding="utf-8"):
        return readme
    return root / "docs" / "REPORT.md"


def _fmt(value: str) -> str:
    try:
        f = float(value)
    except (TypeError, ValueError):
        return value or ""
    return f"{f:.4g}" if not f.is_integer() else str(int(f))


def results_block(root: Path, figures_rel: str) -> str:
    csv_path = root / "results" / "metrics.csv"
    if not csv_path.exists():
        return "_No results yet: run `python tasks.py run`._"
    with csv_path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        return "_No results yet: run `python tasks.py run`._"
    cols = list(rows[0])
    lines = [f"_Generated by VSI on {date.today().isoformat()} from `results/metrics.csv`._", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(_fmt(r.get(c, "")) for c in cols) + " |" for r in rows]
    figures = sorted((root / "docs" / "figures").glob("*.png"))
    if figures:
        lines.append("")
        lines += [f"![{p.stem}]({figures_rel}/{p.name})" for p in figures]
    return "\n".join(lines)


def status_block(root: Path) -> str:
    req = root / "docs" / "REQUIREMENTS.md"
    if not req.exists():
        return ""
    done, total, nxt = progress.summary(req)
    line = f"**Progress / Progresi:** `{progress.bar(done, total)}`"
    return line + (f"  \n**Next step / Hapi i radhës:** {nxt}" if nxt else "  \n**All requirements done / Të gjitha kërkesat u kryen.**")


def copy_figures(root: Path) -> list[Path]:
    out = root / "docs" / "figures"
    for old in out.glob("*.png"):   # keep docs/figures in sync with the latest run
        old.unlink()
    copied = []
    for png in sorted((root / "results").glob("*.png")):
        out.mkdir(parents=True, exist_ok=True)
        shutil.copy2(png, out / png.name)
        copied.append(out / png.name)
    return copied


def update(root: str | Path = ".") -> Path:
    """Refresh the automatic blocks. Returns the file that was written."""
    root = Path(root)
    copy_figures(root)
    path = target_file(root)
    figures_rel = "docs/figures" if path.parent == root else "figures"
    blocks = {"status": status_block(root), "results": results_block(root, figures_rel)}
    if path.exists():
        text = path.read_text(encoding="utf-8")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        text = "# Report (automatic parts)\n\n## Status\n{status}\n\n## Results\n{results}\n".format(
            **{n: "\n".join(_markers(n)) for n in BLOCKS})
    for name, body in blocks.items():
        start, end = _markers(name)
        pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
        if pattern.search(text):
            text = pattern.sub(lambda _: f"{start}\n{body}\n{end}", text)
    path.write_text(text, encoding="utf-8")
    return path
