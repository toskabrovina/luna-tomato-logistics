"""Bundle the project into ONE markdown file for chat AIs without file access (ChatGPT, Gemini, Claude web/app)."""

from __future__ import annotations

from pathlib import Path

PARTS = ["AGENTS.md", "docs/PROBLEM.md", "docs/REQUIREMENTS.md", "docs/DECISIONS.md", "results/metrics.csv"]
CODE_GLOBS = ["src/**/*.py", "tests/**/*.py"]
HEADER = """# Project context (generated by VSI with `python tasks.py context`)

**To the AI:** this is the student's whole project as it is now. Follow the rules in the AGENTS.md section below,
reply in the student's language, work in small steps, give complete file contents with their path, and after each
change ask the student to run `python tasks.py test` (`python3` on macOS / Linux) and paste the output.

{status}
"""
MAX_FILE_CHARS = 15_000


def write_context(root: str | Path = ".", out: str = "CONTEXT.md", include_code: bool = True) -> Path:
    root = Path(root)
    req = root / "docs" / "REQUIREMENTS.md"
    status = ""
    if req.exists():
        from . import progress
        done, total, nxt = progress.summary(req)
        status = f"**Progress:** {progress.bar(done, total)}  \n**Next step:** {nxt or 'all requirements done'}\n"
    chunks = [HEADER.format(status=status)]
    for rel in PARTS:
        p = root / rel
        if p.exists():
            chunks.append(f"\n---\n## {rel}\n\n{p.read_text(encoding='utf-8')[:MAX_FILE_CHARS]}\n")
    if include_code:
        for pattern in CODE_GLOBS:
            for p in sorted(root.glob(pattern)):
                if "__pycache__" in p.parts:
                    continue
                code = p.read_text(encoding="utf-8")[:MAX_FILE_CHARS]
                chunks.append(f"\n---\n## {p.relative_to(root).as_posix()}\n\n```python\n{code}\n```\n")
    path = root / out
    path.write_text("".join(chunks), encoding="utf-8")
    return path
