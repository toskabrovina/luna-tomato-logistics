"""One-word project commands (Windows, macOS, Linux).

    python tasks.py start      everything at once: packages, data, tests, first run, charts, report, progress
    python tasks.py setup      install dependencies (VSI itself is the vsi/ folder)
    python tasks.py data       download the official data files + evaluation code (listed in vsi.json)
    python tasks.py test       run tests (must stay green)
    python tasks.py run        run all algorithms on all instances -> results/metrics.csv
    python tasks.py plots      charts from results/ -> results/*.png
    python tasks.py visualize  diagrams (docs/DIAGRAMS.md + PNGs) and pictures of the instances
    python tasks.py report     refresh the automatic parts of the report (status, results table, charts)
    python tasks.py check      progress from docs/REQUIREMENTS.md + next step
    python tasks.py context    write CONTEXT.md (one file to upload to ChatGPT / Copilot 365 / Gemini web)
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path[:0] = [str(ROOT / "src"), str(ROOT)]
os.chdir(ROOT)
for stream in (sys.stdout, sys.stderr):  # ✅ and progress bars also work in Windows terminals / agent logs
    try:
        stream.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass


def start(_):
    from vsi.start import main
    sys.exit(main(ROOT))


def setup(_):
    if subprocess.call([sys.executable, "-m", "pip", "install", "-r", "requirements.txt"]) != 0:
        print("\nInstall failed. If your system Python blocks installs (Ubuntu, Debian, Homebrew macOS), run "
              "`python3 tasks.py start`: it creates a .venv for this project automatically.")
        sys.exit(1)


def data(_):
    from vsi import data as d
    if not (d.manifest(ROOT).get("data") or d.manifest(ROOT).get("udp")):
        print("No downloadable data for this project (generated by src/generator.py or shipped with the official repo).")
        return
    for path in d.download(ROOT):
        print(path.relative_to(ROOT))


def test(args):
    sys.exit(subprocess.call([sys.executable, "-m", "pytest", "-q", *args]))


def run(args):
    from run import main
    main(args)


def plots(_):
    from vsi import plots as p
    p.main()


def visualize(_):
    from vsi.visualize import main
    for path in main(ROOT):
        print(path.relative_to(ROOT))
    print("docs/DIAGRAMS.md")


def report(_):
    from vsi import progress, report as r
    progress.auto_tick("docs/REQUIREMENTS.md", progress.facts(ROOT))
    print(r.update(ROOT))


def check(_):
    from vsi.check import check as run_check
    run_check("docs/REQUIREMENTS.md")


def context(_):
    from vsi.context import write_context
    print(write_context(ROOT))


COMMANDS = {f.__name__: f for f in (start, setup, data, test, run, plots, visualize, report, check, context)}

if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS:
        print(__doc__)
        sys.exit(1)
    COMMANDS[sys.argv[1]](sys.argv[2:])
